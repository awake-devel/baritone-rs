"""Writes the schematic files the build scenarios of scenarios.py use: a small NBT writer, gzip, and the three formats (Sponge .schem,
Litematica .litematic, MCEdit .schematic).

Test tooling written for this repository from the public descriptions of the formats (the NBT specification, the Sponge schematic
specification and the Litematica file layout the engine reads: see mod/engine/src/schematic/format). The files are generated by run.py into the
game folder's schematics folder before the game starts and are never committed. Deterministic: the same call gives the same bytes.

Cells are given as {(x, y, z): "block name or block[prop=value,...]"}; every other cell of the box is air.
"""
import gzip
import io
import struct


# ---------------------------------------------------------------- NBT

class Tag:
    def __init__(self, value):
        self.value = value


class Byte(Tag):
    ID = 1


class Short(Tag):
    ID = 2


class Int(Tag):
    ID = 3


class Long(Tag):
    ID = 4


class String(Tag):
    ID = 8


class ByteArray(Tag):
    ID = 7


class IntArray(Tag):
    ID = 11


class LongArray(Tag):
    ID = 12


class List(Tag):
    ID = 9

    def __init__(self, item_class, items):
        super().__init__(items)
        self.item_class = item_class


COMPOUND = 10


def _string(out, s):
    b = s.encode("utf-8")
    out.write(struct.pack(">H", len(b)))
    out.write(b)


def _payload(out, tag):
    if isinstance(tag, dict):
        for k, v in tag.items():
            out.write(bytes([_id(v)]))
            _string(out, k)
            _payload(out, v)
        out.write(b"\0")
    elif isinstance(tag, Byte):
        out.write(struct.pack(">b", tag.value))
    elif isinstance(tag, Short):
        out.write(struct.pack(">h", tag.value))
    elif isinstance(tag, Int):
        out.write(struct.pack(">i", tag.value))
    elif isinstance(tag, Long):
        out.write(struct.pack(">q", tag.value))
    elif isinstance(tag, String):
        _string(out, tag.value)
    elif isinstance(tag, ByteArray):
        out.write(struct.pack(">i", len(tag.value)))
        out.write(bytes(b & 0xFF for b in tag.value))
    elif isinstance(tag, IntArray):
        out.write(struct.pack(">i", len(tag.value)))
        for v in tag.value:
            out.write(struct.pack(">i", v))
    elif isinstance(tag, LongArray):
        out.write(struct.pack(">i", len(tag.value)))
        for v in tag.value:
            out.write(struct.pack(">q", v))
    elif isinstance(tag, List):
        out.write(bytes([COMPOUND if tag.item_class is dict else tag.item_class.ID]))
        out.write(struct.pack(">i", len(tag.value)))
        for item in tag.value:
            _payload(out, item)
    else:
        raise TypeError(f"not an NBT value: {tag!r}")


def _id(tag):
    return COMPOUND if isinstance(tag, dict) else tag.ID


def nbt_gzip(root):
    """A gzip file holding a named root compound (the name is empty, as the game writes it). `mtime=0`: the bytes do not depend on the time."""
    out = io.BytesIO()
    out.write(bytes([COMPOUND]))
    _string(out, "")
    _payload(out, root)
    return gzip.compress(out.getvalue(), mtime=0)


# ---------------------------------------------------------------- states

def split_state(text):
    """'minecraft:oak_stairs[facing=east,half=bottom]' -> ('minecraft:oak_stairs', {'facing': 'east', 'half': 'bottom'})."""
    if "[" not in text:
        return text, {}
    name, rest = text.split("[", 1)
    props = dict(p.split("=", 1) for p in rest.rstrip("]").split(",") if p)
    return name, props


AIR = "minecraft:air"


def cell_list(size, cells):
    """The cells of a box in the order the Sponge format and the Litematica format store them: x fastest, then z, then y."""
    w, h, l = size
    return [cells.get((x, y, z), AIR) for y in range(h) for z in range(l) for x in range(w)]


# ---------------------------------------------------------------- Sponge (.schem), versions 1 and 2

def var_int(value):
    out = bytearray()
    value &= 0xFFFFFFFF
    while True:
        b = value & 0x7F
        value >>= 7
        if value:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def sponge(size, cells, version=2):
    w, h, l = size
    names = []
    for c in cell_list(size, cells):
        if c not in names:
            names.append(c)
    if AIR not in names:
        names.append(AIR)
    data = b"".join(var_int(names.index(c)) for c in cell_list(size, cells))
    palette = {n: Int(i) for i, n in enumerate(names)}
    root = {"Version": Int(version), "Width": Short(w), "Height": Short(h), "Length": Short(l), "Palette": palette,
            "BlockData": ByteArray([b - 256 if b > 127 else b for b in data])}
    if version == 2:
        root["DataVersion"] = Int(4189)
    return nbt_gzip(root)


# ---------------------------------------------------------------- Litematica (.litematic), version 7

def bits_per_block(n):
    return max(2, (n - 1).bit_length())


def pack_long_array(values, bits):
    """Entries of `bits` bits each, little-endian, an entry running over into the next long (LitematicaBitArray)."""
    total = len(values) * bits
    longs = [0] * ((total + 63) // 64)
    for i, v in enumerate(values):
        start = i * bits
        for b in range(bits):
            if (v >> b) & 1:
                pos = start + b
                longs[pos // 64] |= 1 << (pos % 64)
    return [v - (1 << 64) if v >= (1 << 63) else v for v in longs]


def litematica(regions):
    """`regions`: {name: {"position": (x, y, z), "size": (w, h, l), "cells": {...}}}. A size may be negative on an axis: the region then reaches
    from its position towards smaller coordinates, and its cells are given in region-local order (x, z, y with x fastest) by their absolute
    value: a cell (x, y, z) is the one at |size| steps from the corner."""
    out = {}
    for name, r in regions.items():
        size = tuple(abs(v) for v in r["size"])
        flat = cell_list(size, r["cells"])
        palette = []
        for c in flat:
            if c not in palette:
                palette.append(c)
        if AIR not in palette:
            palette.insert(0, AIR)
        entries = []
        for c in palette:
            n, props = split_state(c)
            e = {"Name": String(n)}
            if props:
                e["Properties"] = {k: String(v) for k, v in props.items()}
            entries.append(e)
        values = [palette.index(c) for c in flat]
        out[name] = {
            "Position": {"x": Int(r["position"][0]), "y": Int(r["position"][1]), "z": Int(r["position"][2])},
            "Size": {"x": Int(r["size"][0]), "y": Int(r["size"][1]), "z": Int(r["size"][2])},
            "BlockStatePalette": List(dict, entries),
            "BlockStates": LongArray(pack_long_array(values, bits_per_block(len(palette)))),
        }
    return nbt_gzip({"Version": Int(7), "MinecraftDataVersion": Int(4189), "Regions": out})


# ---------------------------------------------------------------- MCEdit (.schematic)

def mcedit(size, ids):
    """`ids`: {(x, y, z): numeric block id}; every other cell is id 0. Index order is y, z, x (x fastest), as the format stores it."""
    w, h, l = size
    blocks = [ids.get((x, y, z), 0) for y in range(h) for z in range(l) for x in range(w)]
    root = {"Width": Short(w), "Height": Short(h), "Length": Short(l), "Materials": String("Alpha"),
            "Blocks": ByteArray([b - 256 if b > 127 else b for b in (v & 0xFF for v in blocks)]),
            "Data": ByteArray([0] * len(blocks))}
    if any(v > 255 for v in blocks):
        add = []
        for i in range(0, len(blocks), 2):
            hi = (blocks[i] >> 8) & 0xF
            lo = ((blocks[i + 1] >> 8) & 0xF) if i + 1 < len(blocks) else 0
            add.append((hi << 4) | lo)
        root["AddBlocks"] = ByteArray([b - 256 if b > 127 else b for b in add])
    return nbt_gzip(root)
